function findSvg(dir) {
  const base = path.join(ICONS_DIR, dir)
  if (!existsSync(base)) return null
  const prefer = [`${dir}-original.svg`, `${dir}-plain.svg`, `${dir}-original-wordmark.svg`]
  for (const name of prefer) {
    const p = path.join(base, name)
    if (existsSync(p)) return p
  }
  const any = readdirSync(base).find((f) => f.endsWith('.svg'))
  return any ? path.join(base, any) : null
}

// Inline `<use xlink:href="#id">` references with the geometry of the element
// they point at. The icon sanitizer (DOMPurify) strips `<use>` but keeps the
// referencing `clip-path`/`fill`, which would leave an empty clipPath that clips
// the whole icon to nothing (e.g. the Go gopher rendered fully blank). Inlining
// makes the def self-contained so it survives sanitization.
function inlineUses(svg) {
  const defs = {}
  svg.replace(/<(path|rect|circle|ellipse|polygon|polyline)\b([^>]*?)\/>/g, (full, tag, attrs) => {
    const id = attrs.match(/\bid="([^"]+)"/)
    if (id) defs[id[1]] = `<${tag}${attrs.replace(/\s*\bid="[^"]+"/, '')}/>`
    return full
  })
  return svg.replace(/<use\b[^>]*?(?:xlink:)?href="#([^"]+)"[^>]*?\/?>(?:<\/use>)?/g, (full, id) =>
    defs[id] ? defs[id] : full
  )
}

function cleanSvg(raw) {
  return inlineUses(
    raw
      .replace(/<\?xml[\s\S]*?\?>/g, '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/>\s+</g, '><')
      .replace(/\s{2,}/g, ' ')
      .trim()
  )
}

const svgs = []
const list = []
const aliasPairs = []
const skipped = []
for (const [token, dir, label, aliases] of CURATED) {
  const file = findSvg(dir)
  if (!file) {
    skipped.push(`${token} (${dir})`)
    continue
  }
  svgs.push([token, cleanSvg(readFileSync(file, 'utf8'))])
  list.push({ token, label, aliases })
  for (const a of aliases) aliasPairs.push([a.toLowerCase(), token])
}

const header = `// AUTO-GENERATED by tooling/scripts/gen-lang-icons.mjs — DO NOT EDIT BY HAND.
// Language logos from devicon (https://devicon.dev), MIT License, inlined as
// static SVG strings. Re-run the generator to refresh.
/* eslint-disable */
`

const svgLines = svgs
  .map(([token, svg]) => `  ${JSON.stringify(token)}: ${JSON.stringify(svg)}`)
  .join(',\n')

const listLines = list
  .map(
    (e) =>
      `  { token: ${JSON.stringify(e.token)}, label: ${JSON.stringify(e.label)}, aliases: ${JSON.stringify(e.aliases)} }`
  )
  .join(',\n')

const aliasLines = aliasPairs
  .map(([a, t]) => `  ${JSON.stringify(a)}: ${JSON.stringify(t)}`)
  .join(',\n')

const out = `${header}
export interface LangIconEntry {
  /** Canonical language token. */
  token: string
  /** Human-readable label for the Settings UI. */
  label: string
  /** Alternate tokens that normalize to \`token\`. */
  aliases: string[]
}

/** Canonical token -> inlined devicon SVG markup. */
export const LANG_ICON_SVGS: Record<string, string> = {
${svgLines}
}

/** Ordered language metadata for the Settings panel (only langs with a logo). */
export const LANG_ICON_LIST: LangIconEntry[] = [
${listLines}
]

/** Alias token -> canonical token. */
export const LANG_ALIASES: Record<string, string> = {
${aliasLines}
}
`

writeFileSync(OUT, out, 'utf8')
